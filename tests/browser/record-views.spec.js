import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
let credentials;
test.beforeAll(()=>{credentials=JSON.parse(execFileSync('php',['tests/browser/seed.php'],{env:{...process.env,DB_CONNECTION:process.env.BROWSER_DB_CONNECTION||'mysql',DB_DATABASE:process.env.BROWSER_DB_DATABASE||'ventas_cuotas_browser'},encoding:'utf8'}));});
test('las filas consultan y las acciones permiten editar duplicar y eliminar',async({page})=>{
 test.setTimeout(90000);page.setDefaultTimeout(15000);const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/login');await page.getByLabel('Correo electrónico').fill(credentials.email);await page.getByLabel('Contraseña',{exact:true}).fill(credentials.password);await page.getByRole('button',{name:'Ingresar al panel'}).click();
 await page.locator('[data-module-card]').filter({has:page.getByRole('heading',{name:'Ventas',exact:true})}).click();
 await page.locator('.workspace-nav-group summary').filter({hasText:'Pagos'}).click();await page.locator('.workspace-navigation nav').getByRole('link',{name:'Métodos de pago',exact:true}).click();
 await page.getByRole('link',{name:'Nuevo método de pago',exact:true}).click();
 await expect(page.locator('[data-record-status] [aria-current=step]')).toHaveText('Borrador');
 await page.getByLabel('Nombre',{exact:true}).fill('Método temporal');
 await page.getByRole('button',{name:'Guardar método de pago',exact:true}).click();
 await expect(page.getByText('Método de pago guardado.',{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Volver a métodos de pago',exact:true}).click();
 let row=page.locator('tbody tr').filter({hasText:'Método temporal'});
 await expect(row.getByRole('link',{name:'Editar',exact:true})).toBeVisible();
 await row.locator('td').nth(1).click();
 await expect(page.getByText('Solo lectura',{exact:true})).toBeVisible();
 await expect(page.getByLabel('Nombre',{exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Guardar método de pago',exact:true})).toHaveCount(0);
 await expect(page.locator('[data-record-status] [aria-current=step]')).toHaveText('Activo');
 await page.screenshot({path:'test-results/record-read-only-desktop.png',fullPage:true});
 await page.locator('.record-actions').getByRole('link',{name:'Editar',exact:true}).click();
 await expect(page.getByLabel('Nombre',{exact:true})).toBeEnabled();
 await page.getByRole('combobox',{name:'Estado',exact:true}).selectOption('0');
 await page.getByRole('button',{name:'Guardar método de pago',exact:true}).click();
 await expect(page.locator('[data-record-status] [aria-current=step]')).toHaveText('Inactivo');
 await page.locator('.record-actions').getByRole('link',{name:'Duplicar',exact:true}).click();
 await expect(page.getByLabel('Nombre',{exact:true})).toHaveValue('Método temporal (copia)');
 await expect(page.locator('[data-record-status] [aria-current=step]')).toHaveText('Borrador');
 await page.getByRole('button',{name:'Guardar método de pago',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/record-actions-mobile.png',fullPage:true});
 page.on('dialog',dialog=>dialog.accept());
 await page.locator('.record-actions').getByRole('button',{name:'Eliminar registro',exact:true}).click();
 await expect(page.getByText('Método de pago eliminado.',{exact:true})).toBeVisible();
 await expect(page.locator('tbody tr').filter({hasText:'Método temporal (copia)'})).toHaveCount(0);
 await page.setViewportSize({width:1440,height:1000});
 row=page.locator('tbody tr').filter({hasText:'Método temporal'});
 await row.locator('td').nth(1).click();
 await expect(page.getByLabel('Nombre',{exact:true})).toHaveValue('Método temporal');
 await page.locator('.record-actions').getByRole('button',{name:'Eliminar registro',exact:true}).click();
 await expect(page.locator('tbody tr').filter({hasText:'Método temporal'})).toHaveCount(0);
 expect(errors).toEqual([]);
});